import fs from "node:fs";
import YAML from "yaml";

const repoRoot = new URL("../../", import.meta.url);
const document = YAML.parse(
  fs.readFileSync(new URL("asyncapi/asyncapi.yaml", repoRoot), "utf8"),
);
const channels = Object.entries(document.channels).map(([name, channel]) => ({
  name,
  address: channel.address,
  kind: channel["x-channel-kind"],
  keys: channel["x-signal-types"],
}));
const signals = channels.filter((channel) => channel.kind === "signal");
const queues = channels.filter((channel) => channel.kind === "durable_queue");
const signalTypeGroups = channels.filter(
  (channel) => Array.isArray(channel.keys) && channel.keys.length > 0,
);

function toPascalCase(value) {
  return value
    .replace(/[-_.]/g, " ")
    .split(" ")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

function toCamelCase(value) {
  const pascal = toPascalCase(value);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

function goConstants() {
  return `// Code generated by AsyncAPI. DO NOT EDIT.
// Source: asyncapi/asyncapi.yaml

package event

// PostgreSQL NOTIFY names for reconstructable realtime signals
const (
${signals.map((signal) => `\tSignal${toPascalCase(signal.name)} = "${signal.address}"`).join("\n")}
)

// Queue names for direct work and durable consumer queues
const (
${queues.map((q) => `\tQueue${toPascalCase(q.name)} = "${q.address}"`).join("\n")}
)

${signalTypeGroups
  .map(
    (group) => `// Signal types for the ${group.name} channel.
const (
${group.keys
  .map(
    (key) =>
      `\tSignalType${toPascalCase(group.name)}${toPascalCase(key)} = "${key}"`,
  )
  .join("\n")}
)`,
  )
  .join("\n\n")}

// Content type constants
const (
\tContentTypeProtobuf = "application/x-protobuf"
\tContentTypeJSON     = "application/json"
)
`;
}

function tsConstants() {
  return `// Code generated by AsyncAPI. DO NOT EDIT.
// Source: asyncapi/asyncapi.yaml

/**
 * PostgreSQL NOTIFY names for reconstructable realtime signals
 */
export const Signals = {
${signals.map((signal) => `  ${toCamelCase(signal.name)}: '${signal.address}',`).join("\n")}
} as const;

/**
 * Queue names for direct work and durable consumer queues
 */
export const Queues = {
${queues.map((q) => `  ${toCamelCase(q.name)}: '${q.address}',`).join("\n")}
} as const;

${signalTypeGroups
  .map(
    (group) => `export const ${toPascalCase(group.name)}SignalTypes = {
${group.keys.map((key) => `  ${toCamelCase(key)}: '${key}',`).join("\n")}
} as const;`,
  )
  .join("\n\n")}

/**
 * Content type constants
 */
export const ContentType = {
  protobuf: 'application/x-protobuf',
  json: 'application/json',
} as const;
`;
}

const target = process.argv[2];
if (target === "go") {
  fs.writeFileSync(new URL("go/event/constants.go", repoRoot), goConstants());
  for (const name of ["pgmq", "translation_source"]) {
    fs.copyFileSync(
      new URL(`runtime/event-${name}.go.tmpl`, import.meta.url),
      new URL(`go/event/${name}.go`, repoRoot),
    );
  }
} else if (target === "ts") {
  fs.writeFileSync(
    new URL("packages/event/src/generated.ts", repoRoot),
    tsConstants(),
  );
} else {
  throw new Error("Usage: generate-event-contracts.mjs go|ts");
}

#!/usr/bin/env node
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const roots = process.argv.slice(2);

if (roots.length === 0) {
  console.error("usage: normalize-generated-ts.mjs <dir> [dir...]");
  process.exit(1);
}

async function* walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      yield* walk(fullPath);
      continue;
    }
    if (entry.isFile() && entry.name.endsWith(".ts")) {
      yield fullPath;
    }
  }
}

async function normalizeFile(filePath) {
  const current = await readFile(filePath, "utf8");
  let normalized = current;

  if (normalized.startsWith("// @generated by protoc-gen-es")) {
    normalized = normalized.replace(/^\/\* eslint-disable \*\/\n\n/mu, "");
  }

  normalized = `${normalized.replace(/\s+$/u, "")}\n`;

  if (normalized !== current) {
    await writeFile(filePath, normalized);
  }
}

for (const root of roots) {
  for await (const filePath of walk(path.resolve(root))) {
    await normalizeFile(filePath);
  }
}

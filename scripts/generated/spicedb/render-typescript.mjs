function directRoleRelationshipProperties() {
  return ["Touch", "Delete"]
    .map(
      (
        operation,
      ) => `  ${operation}Member: (role: RoleID, actor: Actor): RelationshipMutation =>
    createRelationshipMutation(
      createResource("role", role.id),
      "member",
      accountIdentityRelationshipSubject(actor),
      RelationshipOperation.${operation},
    ),`,
    )
    .join("\n");
}

function inheritedRoleRelationshipProperties(model) {
  return model.roleInheritance
    .flatMap(({ role, includes }) =>
      ["Touch", "Delete"].map(
        (
          operation,
        ) => `  ${operation}${pascal(role)}Includes${pascal(includes)}: (): RelationshipMutation =>
    createRelationshipMutation(
      createResource("role", Role.${pascal(role)}().id),
      "member",
      resourceRelationshipSubject("role", Role.${pascal(includes)}().id, "member"),
      RelationshipOperation.${operation},
    ),`,
      ),
    )
    .join("\n");
}

function platformRoleRelationshipProperties(model) {
  return model.roles
    .flatMap((role) =>
      ["Touch", "Delete"].map(
        (
          operation,
        ) => `  ${operation}${pascal(role)}Role: (): RelationshipMutation =>
    createRelationshipMutation(
      platformResource,
      ${quote(role)},
      resourceRelationshipSubject("role", Role.${pascal(role)}().id, "member"),
      RelationshipOperation.${operation},
    ),`,
      ),
    )
    .join("\n");
}


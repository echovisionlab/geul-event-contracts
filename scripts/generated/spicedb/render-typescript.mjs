export function createCan(
  resourceType: string,
  resourceId: string,
  actionName: string,
  permission: string,
): Can {
  const resource = createResource(resourceType, resourceId);
  assertIdentifier("action", actionName);
  assertIdentifier("permission", permission);
  const action = immutable(new ActionDescriptor(actionName, permission));
  return immutable(new CanDescriptor(resource, action));
}

export function createDecision(
  actor: Actor,
  delegation: Delegation,
  can: Can,
): AuthorizationDecision {
  if (
    !(actor instanceof ActorDescriptor) ||
    !(delegation instanceof DelegationDescriptor) ||
    !(can instanceof CanDescriptor)
  ) {
    throw new TypeError("actor, delegation, and can must use supported constructors");
  }
  return immutable(new AuthorizationDecisionDescriptor(actor, delegation, can));
}

export function createRole(id: string): RoleID {
  assertIdentifier("role id", id);
  return immutable(new RoleIDDescriptor(id));
}

export function accountIdentityRelationshipSubject(actor: Actor): RelationshipSubject {
  if (!(actor instanceof ActorDescriptor)) {
    throw new TypeError("actor must use NewAccountIdentityActor");
  }
  return immutable(
    new RelationshipSubjectDescriptor("account_identity", actor.accountIdentityId, ""),
  );
}

export function platformRelationshipSubject(): RelationshipSubject {
  return immutable(new RelationshipSubjectDescriptor("platform", "global", ""));
}

export function resourceRelationshipSubject(
  type: string,
  id: string,
  relation: string,
): RelationshipSubject {
  const resource = createResource(type, id);
  return immutable(
    new RelationshipSubjectDescriptor(resource.type, resource.id, relation),
  );
}

export function createRelationshipMutation(
  resource: Resource,
  relation: string,
  subject: RelationshipSubject,
  operation: RelationshipOperation,
): RelationshipMutation {
  if (!(resource instanceof ResourceDescriptor)) {
    throw new TypeError("resource must use a domain constructor");
  }
  if (!(subject instanceof RelationshipSubjectDescriptor)) {
    throw new TypeError("relationship subject must use a domain constructor");
  }
  if (
    operation !== RelationshipOperation.Touch &&
    operation !== RelationshipOperation.Delete
  ) {
    throw new TypeError("relationship operation is invalid");
  }
  assertIdentifier("relation", relation);
  return immutable(
    new RelationshipMutationDescriptor(resource, relation, subject, operation),
  );
}

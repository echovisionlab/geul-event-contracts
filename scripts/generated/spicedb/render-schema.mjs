export function renderSchema(model) {
  const descriptions = new Map(
    model.definitionModules.map((module) => [
      module.domain,
      module.description,
    ]),
  );
  let previousOwner;
  const blocks = model.definitionNames.map((definitionName) => {
    const owner = model.definitionOwners.get(definitionName);
    const ownerComment =
      owner === previousOwner
        ? ""
        : `// Domain: ${owner} — ${descriptions.get(owner)}\n`;
    previousOwner = owner;
    const capability = model.definitions[definitionName];
    const relations = Object.entries(capability.relations).map(
      ([relation, subjects]) =>
        `  relation ${relation}: ${subjects.join(" | ")}`,
    );
    const permissions = capability.permissions.map(
      (permission) =>
        `  permission ${permission} = ${model.permissionExpressions[definitionName][permission]}`,
    );
    const body = [...relations, ...permissions];
    const definition =
      body.length === 0
        ? `definition ${definitionName} {}`
        : `definition ${definitionName} {\n${body.join("\n")}\n}`;
    return `${ownerComment}${definition}`;
  });

  return `// Code generated by scripts/generated/generate-spicedb-catalog.mjs.
// DO NOT EDIT.
//
// Canonical source: config/spicedb/catalog/{core.yaml,manifest.yaml,domains/*.yaml}
// Catalog fingerprint: ${model.fingerprint}
// Role inheritance tuples:
// role:admin#member@account_identity:<id>
// role:author#member@role:admin#member
// role:user#member@role:author#member

${blocks.join("\n\n")}\n`;
}

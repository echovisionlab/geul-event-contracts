import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

import { loadCatalog } from "./spicedb/catalog-source.mjs";
import { renderGoCore, renderGoDomains } from "./spicedb/render-go.mjs";
import { renderGoTypedSurfaceTest } from "./spicedb/render-go-surface-test.mjs";
import { renderSchema } from "./spicedb/render-schema.mjs";
import {
  renderTypeScriptCore,
  renderTypeScriptDomains,
  renderTypeScriptInternal,
} from "./spicedb/render-typescript.mjs";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const goRoot = path.join(root, "gen/api/policy/v1");
const typeScriptRoot = path.join(
  root,
  "packages/proto/gen/api/policy/v1/spicedb",
);
const schemaPath = path.join(root, "config/spicedb/schema.generated.zed");
const goTypedSurfaceTestPath = path.join(
  root,
  "contracttest/spicedb_typed_surface_generated_test.go",
);
const check = process.argv.includes("--check");

const model = loadCatalog(root);
const schemaSource = renderSchema(model);
const schemaSHA256 = crypto
  .createHash("sha256")
  .update(schemaSource)
  .digest("hex");
const goSources = {
  "spicedb_core.go": renderGoCore(model, schemaSHA256),
  ...renderGoDomains(model),
};
const typeScriptSources = {
  "internal.ts": renderTypeScriptInternal(),
  "core.ts": renderTypeScriptCore(model),
  ...renderTypeScriptDomains(model),
};

const outputs = new Map();
for (const [name, source] of Object.entries(goSources)) {
  outputs.set(
    path.join(goRoot, name),
    execFileSync("gofmt", [], { input: source, encoding: "utf8" }),
  );
}
for (const [name, source] of Object.entries(typeScriptSources)) {
  const file = path.join(typeScriptRoot, name);
  outputs.set(file, await prettier.format(source, { filepath: file }));
}
outputs.set(schemaPath, schemaSource);
outputs.set(
  goTypedSurfaceTestPath,
  execFileSync("gofmt", [], {
    input: renderGoTypedSurfaceTest(model),
    encoding: "utf8",
  }),
);

const generatedHeader =
  "// Code generated by scripts/generated/generate-spicedb-catalog.mjs.";
const staleCandidates = [
  ...(fs.existsSync(goRoot)
    ? fs
        .readdirSync(goRoot)
        .filter((name) => /^spicedb_.*\.go$/.test(name))
        .map((name) => path.join(goRoot, name))
    : []),
  ...(fs.existsSync(typeScriptRoot)
    ? fs
        .readdirSync(typeScriptRoot)
        .filter((name) => name.endsWith(".ts"))
        .map((name) => path.join(typeScriptRoot, name))
    : []),
  ...(fs.existsSync(path.dirname(goTypedSurfaceTestPath))
    ? fs
        .readdirSync(path.dirname(goTypedSurfaceTestPath))
        .filter((name) => /^spicedb_.*_generated_test\.go$/.test(name))
        .map((name) => path.join(path.dirname(goTypedSurfaceTestPath), name))
    : []),
].filter(
  (file) =>
    !outputs.has(file) &&
    fs.readFileSync(file, "utf8").startsWith(generatedHeader),
);

if (check && staleCandidates.length > 0) {
  throw new Error(
    `stale generated SpiceDB files: ${staleCandidates
      .map((file) => path.relative(root, file))
      .join(", ")}`,
  );
}

for (const [file, content] of outputs) {
  if (check) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (current !== content) {
      throw new Error(
        `generated SpiceDB catalog is stale: ${path.relative(root, file)}`,
      );
    }
    continue;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

if (!check) {
  for (const file of staleCandidates) fs.unlinkSync(file);
}
